import { execFile } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { promisify } from 'node:util';
import { canonical, type IniPaths } from './mo2.js';
import type { Instance } from './modManager.js';
import type { Platform } from './platform.js';

const run = promisify(execFile);

/**
 * The few changes this server makes to a Mod Organizer profile, written the way MO2 writes them:
 * CRLF, the header comment kept, and plugins.txt in the system codepage.
 *
 * MO2 holds the profile in memory and writes it back when it exits or starts a program, so an edit
 * made behind its back while it runs is lost. When this instance's MO2 is running, the edit is
 * followed by `ModOrganizer.exe refresh`, which makes it re-read the files from disk
 * (docs/research/2026-10-15-nexus-publishing-and-mo2-refresh.md).
 */

function readLines(file: string, encoding: BufferEncoding): string[] {
    return fs.existsSync(file) ? fs.readFileSync(file, encoding).split(/\r?\n/).filter((line, i, all) => line || i < all.length - 1) : [];
}

function writeLines(file: string, lines: string[], encoding: BufferEncoding): void {
    fs.writeFileSync(file, `${lines.join('\r\n')}\r\n`, encoding);
}

/**
 * Enables a mod: flips `-Name` to `+Name`, or adds `+Name` at the top — the highest priority, so its
 * files win. A mod already listed keeps its place. Returns true when something changed.
 */
export function enableMod(instance: Instance, mod: string): boolean {
    const file = path.join(instance.profileDir, 'modlist.txt');
    const lines = readLines(file, 'utf8');
    const index = lines.findIndex(line => line.slice(1) === mod && /^[+-]/.test(line));
    if (index >= 0) {
        if (lines[index].startsWith('+')) return false;
        lines[index] = `+${mod}`;
    } else {
        const firstEntry = lines.findIndex(line => !line.startsWith('#'));
        lines.splice(firstEntry < 0 ? lines.length : firstEntry, 0, `+${mod}`);
    }
    if (!lines.some(line => line.startsWith('#'))) lines.unshift('# This file was automatically generated by Mod Organizer.');
    writeLines(file, lines, 'utf8');
    return true;
}

/**
 * Activates plugins in plugins.txt and puts each one not there at the end of loadorder.txt, in the
 * order given — after every plugin it could override — or before the plugin `before` names for it, in
 * both files. A plugin already in the load order keeps its place.
 */
export function activatePlugins(
    instance: Instance, plugins: readonly string[], before: ReadonlyMap<string, string> = new Map()
): { activated: string[]; addedToLoadOrder: string[] } {
    const pluginsFile = path.join(instance.profileDir, 'plugins.txt');
    // The system codepage, as MO2 writes it; latin1 is the Western one.
    const lines = readLines(pluginsFile, 'latin1');
    const activated: string[] = [];
    for (const plugin of plugins) {
        const at = lines.findIndex(samePlugin(plugin));
        if (at >= 0 && lines[at].startsWith('*')) continue;
        if (at < 0) insertPlugin(lines, `*${plugin}`, before.get(plugin.toLowerCase()));
        else lines[at] = `*${plugin}`;
        activated.push(plugin);
    }
    if (activated.length > 0) writeLines(pluginsFile, lines, 'latin1');

    const orderFile = path.join(instance.profileDir, 'loadorder.txt');
    const addedToLoadOrder: string[] = [];
    if (fs.existsSync(orderFile)) {
        const order = readLines(orderFile, 'utf8');
        for (const plugin of plugins) {
            if (order.some(samePlugin(plugin))) continue;
            insertPlugin(order, plugin, before.get(plugin.toLowerCase()));
            addedToLoadOrder.push(plugin);
        }
        if (addedToLoadOrder.length > 0) writeLines(orderFile, order, 'utf8');
    }
    return { activated, addedToLoadOrder };
}

/** Whether a line of plugins.txt or loadorder.txt names this plugin, active or not, in any letter case. */
export const samePlugin = (plugin: string) => (line: string) => line.replace(/^\*/, '').toLowerCase() === plugin.toLowerCase();

/** A plugin's line put before the line of the plugin named — or at the end, when it is not listed. */
export function insertPlugin(lines: string[], line: string, beforePlugin: string | undefined): void {
    const at = beforePlugin === undefined ? -1 : lines.findIndex(samePlugin(beforePlugin));
    if (at < 0) lines.push(line);
    else lines.splice(at, 0, line);
}

/** Disables a mod where it stands: `+Name` becomes `-Name`. Returns true when something changed. */
export function disableMod(instance: Instance, mod: string): boolean {
    const file = path.join(instance.profileDir, 'modlist.txt');
    const lines = readLines(file, 'utf8');
    const index = lines.indexOf(`+${mod}`);
    if (index < 0) return false;
    lines[index] = `-${mod}`;
    writeLines(file, lines, 'utf8');
    return true;
}

/**
 * Takes plugins out of plugins.txt and loadorder.txt: Mod Organizer lists no plugin that no enabled mod
 * has, so this is what it writes itself once their mod is disabled. Returns those that were active.
 */
export function removePlugins(instance: Instance, plugins: readonly string[]): string[] {
    const names = new Map(plugins.map(plugin => [plugin.toLowerCase(), plugin]));
    const listed = (line: string) => names.has(line.replace(/^\*/, '').toLowerCase());

    const pluginsFile = path.join(instance.profileDir, 'plugins.txt');
    const lines = readLines(pluginsFile, 'latin1');
    const deactivated = lines.filter(line => line.startsWith('*') && listed(line)).map(line => names.get(line.slice(1).toLowerCase())!);
    if (lines.some(listed)) writeLines(pluginsFile, lines.filter(line => !listed(line)), 'latin1');

    const orderFile = path.join(instance.profileDir, 'loadorder.txt');
    const order = readLines(orderFile, 'utf8');
    if (order.some(listed)) writeLines(orderFile, order.filter(line => !listed(line)), 'utf8');
    return deactivated;
}

// ---------------------------------------------------------------- the running process

/**
 * Whose Mod Organizer runs: this instance's, another's, or none. A process names its program by its
 * path — under Wine, the Windows path, opened here the way the instance's ini paths are.
 */
export async function runningMo2(instance: Instance, platform: Platform, iniPaths: IniPaths): Promise<'none' | 'this' | 'other'> {
    const running = await platform.findProcesses('ModOrganizer.exe');
    if (running.length === 0) return 'none';
    const exe = canonical(path.join(instance.instanceDir, 'ModOrganizer.exe')).toLowerCase();
    const isThis = running.some(process => {
        const native = iniPaths(process.path);
        return native !== undefined && canonical(native).toLowerCase() === exe;
    });
    return isThis ? 'this' : 'other';
}

/**
 * Tells a running Mod Organizer to re-read this instance's profile — only when it is *this*
 * instance's MO2. With none running there is nothing to tell, and `refresh` would start one. With
 * another instance's MO2 running, the command would be forwarded to that one, which never read
 * these files.
 */
export async function refreshIfRunning(instance: Instance, platform: Platform, iniPaths: IniPaths): Promise<'notRunning' | 'refreshed' | 'otherInstanceRunning'> {
    const running = await runningMo2(instance, platform, iniPaths);
    if (running === 'none') return 'notRunning';
    if (running === 'other') return 'otherInstanceRunning';
    await run(path.join(instance.instanceDir, 'ModOrganizer.exe'), ['-p', instance.profile, 'refresh'], { windowsHide: true, timeout: 30_000 });
    return 'refreshed';
}
