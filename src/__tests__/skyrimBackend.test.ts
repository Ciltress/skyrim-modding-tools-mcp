/** A downloaded file the scripted helper can read: its files with their contents, and its installer. */
interface FakeArchive {
    files: Record<string, string>;
    fomod?: { path: string; config: FomodConfig };
}

/**
 * Plays the helper's part: records what it was asked, writes what the real one would. Downloaded
 * files are read from `archives` by their full path; a plugin's masters come from `masters`, by its name.
 * A test that needs another answer to a method puts it into `answers`.
 */
function scriptedHelper(
    archives = new Map<string, FakeArchive>(), masters: Record<string, string[]> = {}, answers: Record<string, (params: any) => any> = {}) {
    const calls: { method: string; params: any }[] = [];
    const archive = (file: string) => {
        const found = archives.get(file);
        if (!found) throw new HelperError('notFound', `No file at '${file}'.`);
        return found;
    };
    let running = false;
    const helper: HelperTransport = {
        get running() { return running; },
        async start() { running = true; },
        stop() { running = false; },
        async call(method: string, params: any = {}): Promise<any> {
            calls.push({ method, params });
            if (answers[method]) return answers[method](params);
            switch (method) {
                case 'hello': return { helper: 'test', protocol: 1 };
                case 'gameVersion': return { version: '1.7.104.0' };
                case 'setLoadOrder': return { plugins: params.plugins.length, missing: [] };
                case 'addOverrides': {
                    const file = 'Weapons/IronSword - 012EB7_Skyrim.esm.yaml';
                    // As the helper does: a record the project already holds is reported, not copied again.
                    if (fs.existsSync(path.join(params.projectPluginDir, file))) {
                        return { added: [], alreadyInProject: [{ formId: '012EB7:Skyrim.esm', file }] };
                    }
                    write(path.join(params.projectPluginDir, file), 'FormKey: 012EB7:Skyrim.esm\nEditorID: IronSword\n');
                    return { added: [{ formId: '012EB7:Skyrim.esm', editorId: 'IronSword', type: 'Weapon', from: 'Skyrim.esm', files: [file] }], alreadyInProject: [] };
                }
                case 'readRecord':
                    return {
                        formId: '012EB7:Skyrim.esm', editorId: 'IronSword', type: 'Weapon', signature: 'WEAP',
                        definedIn: 'Skyrim.esm', winner: 'Skyrim.esm', plugins: ['Skyrim.esm'],
                        versions: [{ plugin: 'Skyrim.esm', winning: true, files: [{ path: 'Weapons/IronSword - 012EB7_Skyrim.esm.yaml', text: 'FormKey: 012EB7:Skyrim.esm\n' }] }]
                    };
                case 'build':
                    write(params.outputPath, `plugin built from ${params.projectPluginDir}`);
                    return { records: 1, masters: ['Skyrim.esm'], headerVersion: params.headerVersion, resolvedLinks: [] };
                case 'serialize':
                    write(path.join(params.outputDir, 'RecordData.yaml'), 'ModKey: MyPatch.esp\n');
                    write(path.join(params.outputDir, 'Weapons', 'IronSword - 012EB7_Skyrim.esm.yaml'), 'FormKey: 012EB7:Skyrim.esm\nEditorID: IronSword\nDamage: 12\n');
                    return { files: 2 };
                case 'readArchive': {
                    const { files, fomod } = archive(params.archivePath);
                    return { files: Object.keys(files), ...(fomod ? { fomod } : {}) };
                }
                case 'extractArchive': {
                    const { files } = archive(params.archivePath);
                    for (const { from, to } of params.files) write(path.join(params.targetDir, to), files[from]);
                    return { written: params.files.length, missing: [] };
                }
                case 'pluginHeaders':
                    return {
                        plugins: params.paths.map((file: string) => ({
                            path: file, masters: masters[path.basename(file)] ?? ['Skyrim.esm'], master: /\.esm$/i.test(file), light: false
                        }))
                    };
                case 'checkRecords': {
                    // As the helper does with fields a record type does not have: refused, naming the file.
                    const files = fs.readdirSync(params.projectPluginDir, { recursive: true }).map(String).filter(f => f.endsWith('.yaml') && f !== 'RecordData.yaml');
                    const invented = files.find(f => fs.readFileSync(path.join(params.projectPluginDir, f), 'utf8').includes('damage:'));
                    if (invented) throw new HelperError('badRecord', `1 record file(s) cannot be built as written: ${invented}: a Weapon has no field damage.`);
                    return { records: files.length };
                }
                default: throw new Error(`unexpected helper call ${method}`);
            }
        }
    };
    return { helper, calls };
}

/**
 * The same system on every machine that runs the suite: no Mod Organizer running (no process table)
 * and no Creation Kit compiler — the Linux side, whatever the suite runs on. Its Wine drives are the
 * machine's own, so the fixture's paths — `C:\…` where the suite runs on Windows — read as they stand.
 */
const hostDrives = (_prefix: string | undefined, letter: string) => letter === 'z' ? '/' : `${letter.toUpperCase()}:\\`;
const quiet = linuxPlatform(path.join(os.tmpdir(), 'skyrim-mcp-no-proc'), hostDrives);

/** A Windows program's path as Wine shows it in a command line: on the machine's own drive, or on Z:, the root. */
const asWinePath = (native: string) => /^[a-z]:/i.test(native) ? native : `Z:${native.replace(/\//g, '\\')}`;

/** A backend on the quiet system, with a process table of its own that is empty until a test starts something in it. */
function makeBackend(options: { nexus?: NexusCatalogue; papyrusCompilerCandidates?: string[]; winePrefix?: string } = {}) {
    const fixture = makeInstance();
    const procRoot = path.join(fixture.root, 'proc');
    const platform = linuxPlatform(procRoot, hostDrives);
    const archives = new Map<string, FakeArchive>();
    const masters: Record<string, string[]> = {};
    const helperAnswers: Record<string, (params: any) => any> = {};
    const { helper, calls } = scriptedHelper(archives, masters, helperAnswers);
    const engine = new SkyrimEngine(new Mo2Manager(fixture.instanceDir, platform, { winePrefix: options.winePrefix }), helper, fixture.projects,
        { platform, papyrusCompilerCandidates: options.papyrusCompilerCandidates });
    const backend = new SkyrimInstanceBackend({ engine, nexus: options.nexus });
    /** Starts a Windows program in the table, as Wine does: its command line is the program's Windows path. */
    const startProgram = (pid: number, exe: string) => write(path.join(procRoot, String(pid), 'cmdline'), `${asWinePath(exe)}\0`);
    /** Puts a downloaded file into the instance's downloads folder, with Mod Organizer's record of it when given. */
    const download = (name: string, content: FakeArchive, meta?: string) => {
        const file = path.join(fixture.instanceDir, 'downloads', name);
        write(file, 'archive bytes');
        if (meta !== undefined) write(`${file}.meta`, meta);
        archives.set(file, content);
        return file;
    };
    return { fixture, backend, calls, engine, startProgram, download, masters, helperAnswers };
}

/** A new project with one record in it: a build of a project without any is refused. */
async function newProjectWithRecord(backend: SkyrimInstanceBackend, projects: string, project: string) {
    await backend.newProject({ project });
    write(path.join(projects, project, 'plugin', 'Weapons', `${project}Sword - 000800_${project}.esp.yaml`), `FormKey: 000800:${project}.esp\nEditorID: ${project}Sword\n`);
}

/** Moves the clock of a folder's files and folders back, so a build made "now" is newer than the sources. */
function age(dir: string, ms = 60_000): void {
    const past = new Date(Date.now() - ms);
    const walk = (d: string) => {
        for (const entry of fs.readdirSync(d, { withFileTypes: true })) {
            const full = path.join(d, entry.name);
            if (entry.isDirectory()) walk(full);
            fs.utimesSync(full, past, past);
        }
    };
    walk(dir);
}

