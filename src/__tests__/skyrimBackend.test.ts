/**
 * What the Skyrim backend actually does, against a real Mod Organizer instance laid out in a
 * temporary folder: an ini, a profile, mods with plugins, a game folder. Only the plugin helper —
 * the .NET process — is a scripted stand-in, because what it does with plugin bytes is its own
 * concern and needs the game's files.
 */

let consoleError: MockInstance;
beforeAll(() => { consoleError = vi.spyOn(console, 'error').mockImplementation(() => { }); });
afterAll(() => { consoleError.mockRestore(); });

const roots: string[] = [];
afterAll(() => { for (const root of roots) fs.rmSync(root, { recursive: true, force: true }); });

function write(file: string, text = ''): void {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
}

const qt = (value: string) => value.replace(/\\/g, '\\\\');

/** A Skyrim SE instance with a high- and a low-priority mod shipping the same plugin. */
function makeInstance(options: { edition?: string; gameName?: string } = {}) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'skyrim-mcp-test-'));
    roots.push(root);
    const game = path.join(root, 'game');
    const instanceDir = path.join(root, 'mo2');

    write(path.join(game, 'SkyrimSE.exe'));
    for (const master of ['Skyrim.esm', 'Update.esm', 'Dawnguard.esm', 'ccExample.esl']) write(path.join(game, 'Data', master));
    write(path.join(game, 'Skyrim.ccc'), 'ccExample.esl\r\nccMissing.esl\r\n');

    write(path.join(instanceDir, 'ModOrganizer.ini'), [
        '[General]',
        `gameName=${options.gameName ?? 'Skyrim Special Edition'}`,
        `gamePath=@ByteArray(${qt(game)})`,
        'selected_profile=@ByteArray(Default)',
        `game_edition=${options.edition ?? 'Steam'}`,
        ''
    ].join('\r\n'));

    const profile = path.join(instanceDir, 'profiles', 'Default');
    write(path.join(profile, 'modlist.txt'),
        '# This file was automatically generated by Mod Organizer.\r\n+HighMod\r\n-DisabledMod\r\n+LowMod\r\n*DLC: Dawnguard\r\n');
    write(path.join(profile, 'loadorder.txt'),
        '# This file was automatically generated by Mod Organizer.\r\nSkyrim.esm\r\nUpdate.esm\r\nDawnguard.esm\r\nccExample.esl\r\nLow.esp\r\nShared.esp\r\nDisabled.esp\r\n');
    write(path.join(profile, 'plugins.txt'), '# This file was automatically generated by Mod Organizer.\r\n*Low.esp\r\n*Shared.esp\r\nDisabled.esp\r\n');

    write(path.join(instanceDir, 'mods', 'HighMod', 'Shared.esp'), 'high');
    write(path.join(instanceDir, 'mods', 'LowMod', 'Shared.esp'), 'low');
    write(path.join(instanceDir, 'mods', 'LowMod', 'Low.esp'));
    write(path.join(instanceDir, 'mods', 'DisabledMod', 'Disabled.esp'));
    fs.mkdirSync(path.join(instanceDir, 'overwrite'), { recursive: true });

    return { root, game, instanceDir, profile, projects: path.join(root, 'projects') };
}

// ---------------------------------------------------------------- reading the instance

describe('reading a Mod Organizer instance', () => {
    it('decodes values the way Qt writes them', () => {
        expect(decodeQtValue('@ByteArray(G:\\\\Steam\\\\Skyrim)')).toBe('G:\\Steam\\Skyrim');
        expect(decodeQtValue('"-D:\\"G:\\\\Data\\""')).toBe('-D:"G:\\Data"');
        expect(decodeQtValue('plain')).toBe('plain');
    });

    it('finds the game, the selected profile and the folders', () => {
        const fixture = makeInstance();
        const instance = readInstance(fixture.instanceDir);
        expect(instance.gameDir).toBe(fixture.game);
        expect(instance.profile).toBe('Default');
        expect(instance.profileDir).toBe(fixture.profile);
        expect(instance.modsDir).toBe(path.join(fixture.instanceDir, 'mods'));
        expect(instance.release).toBe('SkyrimSE');
    });

    it('reads a GOG game as the GOG release', () => {
        expect(readInstance(makeInstance({ edition: 'GOG' }).instanceDir).release).toBe('SkyrimSEGog');
    });

    it('says what to fix when the folder is not an instance, or manages another game', () => {
        expect(() => readInstance(path.join(os.tmpdir(), 'no-such-instance'))).toThrow(InstanceConfigError);
        expect(() => readInstance(path.join(os.tmpdir(), 'no-such-instance'))).toThrow(/SKYRIM_MO2_INSTANCE/);
        expect(() => readInstance(makeInstance({ gameName: 'Fallout 4' }).instanceDir)).toThrow(/not Skyrim Special Edition/);
    });

    it('reads the mod order highest priority first', () => {
        expect(parseModList('# c\n+A\n-B\n*DLC: X\n')).toEqual([
            { name: 'A', enabled: true, managed: true },
            { name: 'B', enabled: false, managed: true },
            { name: 'DLC: X', enabled: true, managed: false }
        ]);
    });

    it('treats the base masters and Creation Club plugins as active, whatever plugins.txt says', () => {
        const instance = readInstance(makeInstance().instanceDir);
        const order = readLoadOrder(instance);
        expect(order.map(p => p.name)).toEqual(
            ['Skyrim.esm', 'Update.esm', 'Dawnguard.esm', 'ccExample.esl', 'Low.esp', 'Shared.esp', 'Disabled.esp']);
        expect(order.filter(p => p.active).map(p => p.name)).toEqual(
            ['Skyrim.esm', 'Update.esm', 'Dawnguard.esm', 'ccExample.esl', 'Low.esp', 'Shared.esp']);
    });

    it('finds each plugin where Mod Organizer would: overwrite, then mods by priority, then the game', () => {
        const fixture = makeInstance();
        const instance = readInstance(fixture.instanceDir);
        let files = resolvePluginFiles(instance, readModList(instance));
        expect(files.get('shared.esp')).toBe(path.join(fixture.instanceDir, 'mods', 'HighMod', 'Shared.esp'));
        expect(files.get('low.esp')).toBe(path.join(fixture.instanceDir, 'mods', 'LowMod', 'Low.esp'));
        expect(files.get('skyrim.esm')).toBe(path.join(fixture.game, 'Data', 'Skyrim.esm'));
        // A disabled mod's files are not there at all.
        expect(files.has('disabled.esp')).toBe(false);

        write(path.join(fixture.instanceDir, 'overwrite', 'Shared.esp'), 'saved by the Creation Kit');
        files = resolvePluginFiles(instance, readModList(instance));
        expect(files.get('shared.esp')).toBe(path.join(fixture.instanceDir, 'overwrite', 'Shared.esp'));
    });
});

